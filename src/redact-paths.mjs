/**
 * 群聊出站路径脱敏（唯一实现）。
 *
 * 2026-11 真实事故：表情包 Markdown 图片行降级成文字发进群，把
 * 「盘符:\Users\用户名\…」整条路径（含用户名/目录结构）公开了。
 * 现在图片行在发送前会被剥离成图片段；这个函数是最后一层兜底：
 * 任何来源（模型、工具、控制台）写进群聊文本的本机路径一律替换掉。
 *
 * 注意 `http://` 里含 `p:/`，所以盘符正则必须要求前面不是字母数字，
 * 否则会把正常网址一起吞掉（有单测覆盖）。
 */
export function redactLocalPaths(text) {
  return String(text ?? '')
    .replace(/file:\/\/\/?[^\s)"'<>]+/gi, '[本机路径已隐藏]')
    .replace(/(?<![A-Za-z0-9])[A-Za-z]:[\\/][^\s)"'<>]*/g, '[本机路径已隐藏]')
    .replace(/\\\\[^\s)"'<>]+/g, '[本机路径已隐藏]');
}
